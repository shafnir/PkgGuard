  /**
   * Validate a command locally using basic heuristics.
   */
  validate(command: string): LocalValidationResult {
    const startTime = Date.now();
    const extractionResult = PackageExtractor.extractPackages(command);
    
    if (!extractionResult.isInstallCommand || extractionResult.packages.length === 0) {
      return {
        isValid: true,
        packages: [],
        recommendation: "No packages to validate in this command",
        processingTime: Date.now() - startTime,
        source: "local"
      };
    }

    const packages = extractionResult.packages.map(pkg => {
      const risks = this.analyzePackageRisks(pkg.name, pkg.ecosystem);
      const trustLevel = this.determineTrustLevel(pkg.name, risks);

      return {
        name: pkg.name,
        ecosystem: pkg.ecosystem,
        score: null,
        trustLevel,
        risks,
        processingTime: 0
      };
    });

    const isValid = packages.every(pkg => pkg.trustLevel !== "low");
    const recommendation = this.generateRecommendation(packages);

    return {
      isValid,
      packages,
      recommendation,
      processingTime: Date.now() - startTime,
      source: "local"
    };
  }

  /**
   * Analyze package risks using heuristics.
   */
  private analyzePackageRisks(packageName: string, ecosystem: "python" | "javascript"): string[] {
    const risks: string[] = [];

    // Check against known malicious packages
    if (this.knownMaliciousPackages.has(packageName)) {
      risks.push("Known malicious package");
    }

    // Check against suspicious patterns
    for (const pattern of this.suspiciousPatterns) {
      if (pattern.test(packageName)) {
        risks.push("Suspicious package name pattern");
        break;
      }
    }

    // Basic name analysis
    if (packageName.length < 3) {
      risks.push("Suspiciously short package name");
    }

    if (packageName.length > 50) {
      risks.push("Suspiciously long package name");
    }

    // Check for typosquatting indicators
    if (this.isPotentialTyposquatting(packageName, ecosystem)) {
      risks.push("Potential typosquatting");
    }

    // Check for confusing characters
    if (/[Il0O]{2,}/.test(packageName)) {
      risks.push("Contains confusing characters (I, l, 0, O)");
    }

    // Check for long number sequences
    if (/\d{4,}/.test(packageName)) {
      risks.push("Contains long number sequence");
    }

    // Check for excessive special characters
    if (/[._-]{3,}/.test(packageName)) {
      risks.push("Excessive special characters");
    }

    // Check for mixed case inconsistencies
    if (/[A-Z]/.test(packageName) && /[a-z]/.test(packageName) && ecosystem === "python") {
      risks.push("Mixed case (unusual for Python packages)");
    }

    return risks;
  }

  /**
   * Check if package name is potential typosquatting.
   */
  private isPotentialTyposquatting(packageName: string, ecosystem: "python" | "javascript"): boolean {
    // Common popular packages to check against
    const popularPackages = {
      python: [
        'numpy', 'pandas', 'requests', 'django', 'flask', 'tensorflow', 'torch',
        'scikit-learn', 'matplotlib', 'seaborn', 'beautifulsoup4', 'pillow',
        'opencv-python', 'sqlalchemy', 'pytest', 'click', 'jinja2', 'pyyaml',
        'cryptography', 'dateutil', 'pytz', 'six', 'urllib3', 'certifi',
        'setuptools', 'wheel', 'pip'
      ],
      javascript: [
        'react', 'lodash', 'express', 'axios', 'jquery', 'vue', 'angular',
        'bootstrap', 'moment', 'underscore', 'async', 'request', 'debug',
        'chalk', 'commander', 'colors', 'fs-extra', 'glob', 'yargs',
        'inquirer', 'joi', 'bcrypt', 'jsonwebtoken', 'passport', 'mongoose',
        'sequelize', 'socket.io', 'nodemailer', 'multer', 'morgan', 'cors',
        'helmet', 'dotenv', 'uuid', 'validator', 'cheerio', 'puppeteer',
        'sharp', 'redis', 'pg', 'mysql', 'mongodb', 'winston', 'jest',
        'mocha', 'eslint', 'prettier', 'webpack', 'babel', 'typescript',
        'rollup', 'vite', 'next', 'nuxt', 'gatsby', 'svelte', 'tailwindcss'
      ]
    };

    const popular = popularPackages[ecosystem];
    
    // Check for close matches (edit distance)
    for (const pop of popular) {
      if (this.editDistance(packageName, pop) <= 2 && packageName !== pop) {
        return true;
      }
    }

    return false;
  }

  /**
   * Calculate edit distance between two strings.
   */
  private editDistance(a: string, b: string): number {
    const matrix = [];

    for (let i = 0; i <= b.length; i++) {
      matrix[i] = [i];
    }

    for (let j = 0; j <= a.length; j++) {
      matrix[0]![j] = j;
    }

    for (let i = 1; i <= b.length; i++) {
      for (let j = 1; j <= a.length; j++) {
        if (b.charAt(i - 1) === a.charAt(j - 1)) {
          matrix[i]![j] = matrix[i - 1]![j - 1]!;
        } else {
          matrix[i]![j] = Math.min(
            matrix[i - 1]![j - 1]! + 1,
            matrix[i]![j - 1]! + 1,
            matrix[i - 1]![j]! + 1
          );
        }
      }
    }

    return matrix[b.length]![a.length]!;
  }

  /**
   * Determine trust level based on risks.
   */
  private determineTrustLevel(
    _packageName: string,
    risks: string[]
  ): "high" | "medium" | "low" | "ignored" | "unknown" {
    if (risks.some(risk => 
      risk.includes("Known malicious") || 
      risk.includes("Potential typosquatting")
    )) {
      return "low";
    }

    if (risks.length >= 2) {
      return "medium";
    }

    if (risks.length === 1) {
      return "medium";
    }

    return "unknown";
  }

  /**
   * Generate recommendation based on analysis.
   */
  private generateRecommendation(
    packages: Array<{ name: string; trustLevel: string; risks: string[] }>
  ): string {
    const maliciousPackages = packages.filter(pkg => pkg.trustLevel === "low");
    const suspiciousPackages = packages.filter(pkg => pkg.trustLevel === "medium");

    if (maliciousPackages.length > 0) {
      const names = maliciousPackages.map(pkg => pkg.name).join(", ");
      return `🚨 BLOCKED: Packages ${names} are flagged as high risk. Do not install.`;
    }

    if (suspiciousPackages.length > 0) {
      const names = suspiciousPackages.map(pkg => pkg.name).join(", ");
      return `⚠️ WARNING: Packages ${names} appear suspicious. Verify manually before installation.`;
    }

    return `❓ OFFLINE MODE: Limited security analysis available. Verify packages manually at their official registries.`;
  }
