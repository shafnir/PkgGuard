/**
 * Configuration management for LSP components.
 * Centralizes all configurable values to avoid hardcoded constants.
 */

import * as vscode from 'vscode';

export interface LSPServerConfig {
  maxRequestsPerMinute: number;
  authTokenLength: number;
  cleanupIntervalMs: number;
}

export interface LSPClientConfig {
  maxRetries: number;
  retryDelayMs: number;
  healthCheckIntervalMs: number;
  requestTimeoutMs: number;
}

export interface AnalysisConfig {
  cacheTTL: number;
  trustThresholds: {
    python: { high: number; medium: number };
    javascript: { high: number; medium: number };
  };
  scoringWeights: {
    existence: number;
    downloads: number;
    recency: number;
    maintainers: number;
    vulnerabilityPenalty: number;
    typosquattingPenalty: number;
  };
}

export interface LocalValidationConfig {
  minPackageNameLength: number;
  maxNumberSequenceLength: number;
  confusingCharacterPattern: RegExp;
  knownMaliciousPackages: string[];
}

